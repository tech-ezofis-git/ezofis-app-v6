"""Request bodies. Tenant is never accepted from the body — only from the validated context."""

from __future__ import annotations

import uuid
from datetime import date
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.report_agent_v2.domain.spec import Condition

Visibility = Literal["Private", "Public", "Selected Users", "Selected Groups"]


class _Body(BaseModel):
    model_config = ConfigDict(extra="ignore", populate_by_name=True, str_strip_whitespace=True)


class SourceSelection(_Body):
    source_type: Literal["Workflow", "Folder"] = Field(alias="sourceType")
    workflow_id: uuid.UUID | None = Field(default=None, alias="workflowId")
    workflow_name: str | None = Field(default=None, alias="workflowName", max_length=256)
    repository_id: uuid.UUID | None = Field(default=None, alias="repositoryId")
    repository_name: str | None = Field(default=None, alias="repositoryName", max_length=256)

    @model_validator(mode="after")
    def _source_present(self) -> "SourceSelection":
        if self.source_type == "Workflow" and not (self.workflow_id or self.workflow_name):
            raise ValueError("workflowId or workflowName is required when sourceType is Workflow.")
        if self.source_type == "Folder" and not (self.repository_id or self.repository_name):
            raise ValueError("repositoryId or repositoryName is required when sourceType is Folder.")
        return self


class _SpecPayload(_Body):
    """A reportSpec in the V6 "report AI definition" format, as returned by /definitions/preview.

    Its "agentSpec.spec" part is the executable v2 spec; its "columns" / "filters" / "title" /
    "objective" carry the user's edits from the wizard, applied on top of it.
    """

    report_spec: dict | None = Field(default=None, alias="reportSpec")
    agent_spec: dict | None = Field(default=None, alias="agentSpec")

    def has_spec(self) -> bool:
        return bool(self.agent_spec or (self.report_spec or {}).get("agentSpec"))

    def spec_dict(self) -> dict:
        """The executable v2 spec: reportSpec.agentSpec.spec, or agentSpec(.spec) when sent directly."""
        agent = self.agent_spec or (self.report_spec or {}).get("agentSpec") or {}
        spec = agent.get("spec", agent) if isinstance(agent, dict) else None
        if not isinstance(spec, dict) or not spec:
            raise ValueError("reportSpec.agentSpec.spec is required: send the reportSpec returned by /definitions/preview.")
        return spec


class CreateDefinitionRequest(SourceSelection):
    prompt: str = Field(min_length=5, max_length=4000)
    name: str | None = Field(default=None, max_length=256)
    description: str | None = Field(default=None, max_length=2000)
    visibility: Visibility | None = None
    shared_users: list[uuid.UUID] = Field(default_factory=list, alias="sharedUsers", max_length=500)
    shared_groups: list[uuid.UUID] = Field(default_factory=list, alias="sharedGroups", max_length=200)
    # Same as V6 ReportAiPromptRequest.SessionId; generated ("report-<guid>") when omitted.
    session_id: str | None = Field(default=None, alias="sessionId", max_length=128)


class PreviewDefinitionRequest(CreateDefinitionRequest, _SpecPayload):
    """POST /definitions/preview: generate from a prompt, or (with reportSpec) re-run an
    already generated spec with the user's edits applied. The spec path never calls the LLM."""

    prompt: str | None = Field(default=None, min_length=1, max_length=4000)

    @model_validator(mode="after")
    def _prompt_or_spec(self) -> "PreviewDefinitionRequest":
        if not self.has_spec() and (not self.prompt or len(self.prompt.strip()) < 5):
            raise ValueError("Send a prompt (at least 5 characters) or the reportSpec returned by a previous preview.")
        return self


class SaveDefinitionRequest(SourceSelection, _SpecPayload):
    """POST /definitions/save: store a definition already generated by /definitions/preview.

    No LLM call: the previewed reportSpec (its "agentSpec" part) is re-validated against the
    live source and saved as-is, so what the user saw is exactly what gets saved.
    """

    report_id: uuid.UUID | None = Field(default=None, alias="id")  # set to overwrite an existing report
    prompt: str = Field(min_length=1, max_length=4000)
    name: str | None = Field(default=None, max_length=256)
    description: str | None = Field(default=None, max_length=2000)
    visibility: Visibility | None = None
    shared_users: list[uuid.UUID] = Field(default_factory=list, alias="sharedUsers", max_length=500)
    shared_groups: list[uuid.UUID] = Field(default_factory=list, alias="sharedGroups", max_length=200)
    session_id: str | None = Field(default=None, alias="sessionId", max_length=128)
    model: str | None = Field(default=None, max_length=128)  # model that generated the preview (audit only)
    status: Literal["Draft", "Published"] | None = None  # omitted: new reports are Draft, updates keep theirs


class RegenerateDefinitionRequest(_Body):
    """PUT: regenerate the spec. Omitted prompt = reuse the last prompt (e.g. after a form change)."""

    prompt: str | None = Field(default=None, min_length=5, max_length=4000)
    name: str | None = Field(default=None, max_length=256)
    description: str | None = Field(default=None, max_length=2000)
    visibility: Visibility | None = None
    shared_users: list[uuid.UUID] | None = Field(default=None, alias="sharedUsers", max_length=500)
    shared_groups: list[uuid.UUID] | None = Field(default=None, alias="sharedGroups", max_length=200)


class ExecuteReportRequest(_Body):
    as_of_date: date | None = Field(default=None, alias="asOfDate")
    filters: list[Condition] = Field(default_factory=list, max_length=20)
    limit: int | None = Field(default=None, ge=1, le=100_000)


class HighlightRule(_Body):
    color: str = Field(max_length=32)
    op: str = Field(max_length=32)
    value: str | int | float | bool | None = None
    value2: str | int | float | None = None
    compare_field: str | None = Field(default=None, alias="compareField", max_length=256)
    label: str | None = Field(default=None, max_length=128)


class ColumnHighlight(_Body):
    rules: list[HighlightRule] = Field(default_factory=list, max_length=20)
    default: str | None = Field(default=None, max_length=32)


class HighlightsRequest(_Body):
    """PUT /definitions/{id}/highlights: column key -> highlight rules (null or no rules clears it)."""

    columns: dict[str, ColumnHighlight | None] = Field(max_length=100)
