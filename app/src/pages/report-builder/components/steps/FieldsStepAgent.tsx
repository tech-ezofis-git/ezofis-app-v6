import { useLingui } from '@lingui/react/macro'
import { useDebouncedValue } from '@mantine/hooks'
import { AnimatePresence, motion } from 'motion/react'
import { useEffect, useMemo, useRef, useState } from 'react'
import type { ReportSpec, ReportSpecColumn } from '@/api/v6/reportAgent'
import { runReportAiReport } from '@/api/v6/reportAgent'
import Button from '@/components/base/button/Button'
import IconButton from '@/components/base/button/IconButton'
import Icon from '@/components/base/icon/Icon'
import InputSelect from '@/components/base/inputs/InputSelect'
import InputText from '@/components/base/inputs/InputText'
import AiBrandIcon from '@/components/common/AiBrandIcon'
import cn from '@/utils/cn'
import type { ReportFieldSetting } from '../../types'
import useReportBuilderDraftStore from '../../stores/useReportBuilderDraftStore'
import { createDefaultFieldSetting } from '../../types'
import {
  agentColumnCatalog,
  agentRunToReportRunResult,
  buildAgentConfigFromDraft,
} from '../../utils/agentReport'
import FieldsPreviewTable from './FieldsPreviewTable'
import StatusRulesEditor from './StatusRulesEditor'

type ColumnKind = 'agent' | 'default' | 'userdefined'

const KIND_BADGE: Record<ColumnKind, string> = {
  agent: 'border-primary-5 bg-primary-3 text-primary-11',
  default: 'border-gray-4 bg-gray-2 text-gray-11',
  userdefined: 'border-blue-5 bg-blue-3 text-blue-11',
}

const kindOf = (column?: ReportSpecColumn): ColumnKind =>
  column?.kind === 'agent' || column?.kind === 'default'
    ? column.kind
    : 'userdefined'

// Both lists share one height so they line up side by side, and stay within
// the viewport instead of pushing the wizard footer off-screen.
const LIST_HEIGHT = 'max-h-[min(420px,50vh)] md:h-[min(420px,50vh)]'

const PREVIEW_ROWS = 10
const PREVIEW_DEBOUNCE_MS = 600

/**
 * Fields step for reports generated by the report agent: columns come from
 * the agent's reportSpec palettes rather than a form schema. Selected keys,
 * labels and highlight rules are written to the draft and sent back to the
 * agent on Run / save; every column/filter change re-runs a live preview.
 */
const FieldsStepAgent = () => {
  const { t } = useLingui()
  const draft = useReportBuilderDraftStore((state) => state.draft)
  const setDraft = useReportBuilderDraftStore((state) => state.setDraft)
  const [expandedKey, setExpandedKey] = useState<string | null>(null)
  const [search, setSearch] = useState('')

  const kindLabel: Record<ColumnKind, string> = {
    agent: t`Agent`,
    default: t`Default`,
    userdefined: t`Form`,
  }

  const catalog = useMemo(
    () =>
      draft.agent
        ? agentColumnCatalog(draft.agent.reportSpec as unknown as ReportSpec)
        : [],
    [draft.agent],
  )
  const catalogByKey = useMemo(
    () => new Map(catalog.map((column) => [column.key, column])),
    [catalog],
  )

  // Every search word must appear somewhere in the label or key, in any
  // order; underscores count as spaces so "quote2 total" finds quote2_Total.
  const searchWords = search.trim().toLowerCase().split(/\s+/).filter(Boolean)
  const unselected = catalog.filter(
    (column) => !draft.fields.includes(column.key),
  )
  const available = unselected.filter((column) => {
    const haystack = `${column.label} ${column.key}`
      .toLowerCase()
      .replace(/_/g, ' ')
    return searchWords.every((word) => haystack.includes(word))
  })

  // Same icons the app uses elsewhere: lucide file-text for Forms, the AI
  // brand icon for agent-generated columns, a database glyph for the
  // workflow's default/system columns.
  const renderKindIcon = (kind: ColumnKind) =>
    kind === 'agent' ? (
      <AiBrandIcon className='size-4' variant='outline-purple' />
    ) : (
      <Icon
        className={cn(
          'size-4',
          kind === 'userdefined' ? 'text-blue-11' : 'text-gray-10',
        )}
        name={kind === 'userdefined' ? 'lucide:file-text' : 'lucide:database'}
      />
    )

  const settingFor = (key: string) =>
    draft.fieldSettings[key] ||
    createDefaultFieldSetting(catalogByKey.get(key)?.label || key)

  const addColumn = (key: string) => {
    setDraft({
      fields: [...draft.fields, key],
      fieldSettings: { ...draft.fieldSettings, [key]: settingFor(key) },
    })
  }

  const removeColumn = (key: string) => {
    setDraft({ fields: draft.fields.filter((id) => id !== key) })
    if (expandedKey === key) setExpandedKey(null)
  }

  const moveColumn = (key: string, direction: -1 | 1) => {
    const index = draft.fields.indexOf(key)
    const target = index + direction
    if (index < 0 || target < 0 || target >= draft.fields.length) return
    const next = [...draft.fields]
    ;[next[index], next[target]] = [next[target], next[index]]
    setDraft({ fields: next })
  }

  const updateSetting = (key: string, patch: Partial<ReportFieldSetting>) => {
    setDraft({
      fieldSettings: {
        ...draft.fieldSettings,
        [key]: { ...settingFor(key), ...patch },
      },
    })
  }

  // ---- Live preview via /report-agent/run ---------------------------------
  // Only columns and filters change the data; labels/highlights are applied
  // client-side, so they don't trigger a new run.
  const runKey = JSON.stringify([draft.fields, draft.filters])
  const [debouncedRunKey] = useDebouncedValue(runKey, PREVIEW_DEBOUNCE_MS)
  const [previewRows, setPreviewRows] = useState<Record<string, string>[]>([])
  const [previewTotal, setPreviewTotal] = useState<number | null>(null)
  const [previewError, setPreviewError] = useState('')
  const [isPreviewing, setIsPreviewing] = useState(false)
  const runIdRef = useRef(0)

  const runPreview = async () => {
    if (!draft.agent || draft.fields.length === 0) {
      setPreviewRows([])
      setPreviewTotal(null)
      return
    }
    const runId = ++runIdRef.current
    setIsPreviewing(true)
    setPreviewError('')
    const config = buildAgentConfigFromDraft(draft.agent, draft)
    const { data, error } = await runReportAiReport(config.id, {
      page: 1,
      pageSize: PREVIEW_ROWS,
      reportPrompt: config.reportPrompt,
      reportSpec: config.reportSpec,
    })
    // A newer run started while this one was in flight; drop the stale result.
    if (runId !== runIdRef.current) return
    setIsPreviewing(false)
    if (error || !data) {
      setPreviewError(error || t`Failed to run the report`)
      return
    }
    const result = agentRunToReportRunResult(data, {
      domain: draft.domain,
      name: draft.name,
      reportId: null,
    })
    setPreviewRows(result.rows)
    setPreviewTotal(result.rowCount)
  }

  useEffect(() => {
    void runPreview()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [debouncedRunKey])

  const isPreviewPending = isPreviewing || runKey !== debouncedRunKey

  const previewColumns = draft.fields.map((key) => ({
    id: key,
    label: settingFor(key).label,
    sampleType: 'text' as const,
  }))

  return (
    <div className='flex flex-col gap-5'>
      <div className='grid grid-cols-1 gap-4 md:grid-cols-[minmax(0,1.6fr)_minmax(0,1fr)]'>
        {/* Selected columns */}
        <section className='flex min-w-0 flex-col overflow-hidden rounded-xl border border-gray-3 bg-surface shadow-sm'>
          <header className='flex items-center gap-2.5 border-b border-gray-3 bg-gray-1/60 px-3.5 py-2.5'>
            <span className='flex size-7 items-center justify-center rounded-lg bg-primary-3 text-primary-11'>
              <Icon className='size-4' name='lucide:columns-3' />
            </span>
            <div className='min-w-0 flex-1'>
              <p className='text-13 font-semibold text-gray-13'>{t`Selected columns`}</p>
              <p className='text-11 text-gray-9'>{t`Shown in this order in the report`}</p>
            </div>
            <span className='rounded-full bg-primary-3 px-2 py-0.5 text-11 font-semibold text-primary-11'>
              {draft.fields.length}
            </span>
          </header>

          <div className={cn('ez-scrollbar overflow-y-auto p-2', LIST_HEIGHT)}>
            {draft.fields.length === 0 ? (
              <div className='flex h-full min-h-40 flex-col items-center justify-center gap-2 text-center'>
                <Icon
                  className='size-6 text-gray-7'
                  name='lucide:mouse-pointer-click'
                />
                <p className='text-13 text-gray-10'>{t`No columns selected yet.`}</p>
                <p className='text-12 text-gray-9'>{t`Add columns from the list.`}</p>
              </div>
            ) : (
              <ul className='flex flex-col gap-1.5'>
                <AnimatePresence initial={false}>
                  {draft.fields.map((key, index) => {
                    const column = catalogByKey.get(key)
                    const kind = kindOf(column)
                    const setting = settingFor(key)
                    const isExpanded = expandedKey === key
                    const hasHighlight =
                      setting.colType === 'status' &&
                      Boolean(setting.statusRules?.length)

                    return (
                      <motion.li
                        animate={{ opacity: 1, y: 0 }}
                        exit={{ opacity: 0, x: -12 }}
                        initial={{ opacity: 0, y: 6 }}
                        key={key}
                        transition={{ duration: 0.18 }}
                        layout
                        className={cn(
                          'group rounded-lg border transition-colors',
                          isExpanded
                            ? 'border-primary-6 bg-primary-1'
                            : 'border-gray-3 bg-surface hover:border-gray-5 hover:bg-gray-1/60',
                        )}
                      >
                        <div className='flex items-center gap-2 px-2 py-1.5'>
                          <span className='flex size-6 shrink-0 items-center justify-center rounded-md bg-gray-2 text-11 font-semibold text-gray-10'>
                            {index + 1}
                          </span>
                          <div className='min-w-0 flex-1'>
                            <div className='flex min-w-0 items-center gap-1.5'>
                              <p className='truncate text-13 font-medium text-gray-12'>
                                {setting.label}
                              </p>
                              {kind === 'agent' && (
                                <AiBrandIcon
                                  className='size-3 shrink-0'
                                  variant='outline-purple'
                                />
                              )}
                            </div>
                            <p className='truncate text-11 text-gray-9'>
                              {key}
                              {column?.formula ? ` · ${column.formula}` : ''}
                            </p>
                          </div>
                          {hasHighlight && (
                            <span className='hidden shrink-0 rounded-full border border-primary-5 bg-primary-3 px-2 py-0.5 text-11 text-primary-11 sm:inline'>
                              {t`Highlighted`}
                            </span>
                          )}
                          <span
                            className={cn(
                              'hidden shrink-0 rounded-full border px-2 py-0.5 text-11 sm:inline',
                              KIND_BADGE[kind],
                            )}
                          >
                            {kindLabel[kind]}
                          </span>
                          <div
                            className={cn(
                              'flex shrink-0 items-center transition-opacity',
                              isExpanded
                                ? 'opacity-100'
                                : 'opacity-70 group-hover:opacity-100',
                            )}
                          >
                            <IconButton
                              ariaLabel={t`Move ${setting.label} up`}
                              color='gray'
                              disabled={index === 0}
                              icon='lucide:chevron-up'
                              size='sm'
                              variant='ghost'
                              onClick={() => moveColumn(key, -1)}
                            />
                            <IconButton
                              ariaLabel={t`Move ${setting.label} down`}
                              color='gray'
                              disabled={index === draft.fields.length - 1}
                              icon='lucide:chevron-down'
                              size='sm'
                              variant='ghost'
                              onClick={() => moveColumn(key, 1)}
                            />
                            <IconButton
                              ariaLabel={t`Configure ${setting.label}`}
                              color={isExpanded ? 'primary' : 'gray'}
                              icon='lucide:settings-2'
                              size='sm'
                              variant='ghost'
                              onClick={() =>
                                setExpandedKey(isExpanded ? null : key)
                              }
                            />
                            <IconButton
                              ariaLabel={t`Remove ${setting.label}`}
                              color='red'
                              icon='lucide:x'
                              size='sm'
                              variant='ghost'
                              onClick={() => removeColumn(key)}
                            />
                          </div>
                        </div>

                        <AnimatePresence initial={false}>
                          {isExpanded && (
                            <motion.div
                              animate={{ height: 'auto', opacity: 1 }}
                              className='overflow-hidden'
                              exit={{ height: 0, opacity: 0 }}
                              initial={{ height: 0, opacity: 0 }}
                              transition={{ duration: 0.2 }}
                            >
                              <div className='mx-2 mb-2 grid grid-cols-1 gap-3 rounded-lg border border-gray-3 bg-surface p-3 sm:grid-cols-2'>
                                <InputText
                                  label={t`Column Label`}
                                  value={setting.label}
                                  onChange={(value) =>
                                    updateSetting(key, { label: value })
                                  }
                                />
                                <InputSelect
                                  label={t`Column Type`}
                                  options={[
                                    { id: 'value', name: t`Plain Value` },
                                    { id: 'status', name: t`Highlighted` },
                                  ]}
                                  value={{
                                    id: setting.colType,
                                    name:
                                      setting.colType === 'status'
                                        ? t`Highlighted`
                                        : t`Plain Value`,
                                  }}
                                  onChange={(option) =>
                                    updateSetting(key, {
                                      colType:
                                        (option?.id as ReportFieldSetting['colType']) ||
                                        'value',
                                      statusBase: key,
                                    })
                                  }
                                />
                                {setting.colType === 'status' && (
                                  <StatusRulesEditor
                                    statusDefault={setting.statusDefault}
                                    statusRules={setting.statusRules || []}
                                    onChange={(patch) =>
                                      updateSetting(key, patch)
                                    }
                                  />
                                )}
                              </div>
                            </motion.div>
                          )}
                        </AnimatePresence>
                      </motion.li>
                    )
                  })}
                </AnimatePresence>
              </ul>
            )}
          </div>
        </section>

        {/* Available columns */}
        <section className='flex min-w-0 flex-col overflow-hidden rounded-xl border border-gray-3 bg-surface shadow-sm'>
          <header className='flex flex-col gap-2 border-b border-gray-3 bg-gray-1/60 px-3.5 py-2.5'>
            <div className='flex items-center gap-2.5'>
              <span className='flex size-7 items-center justify-center rounded-lg bg-blue-3 text-blue-11'>
                <Icon className='size-4' name='lucide:list-plus' />
              </span>
              <div className='min-w-0 flex-1'>
                <p className='text-13 font-semibold text-gray-13'>{t`Available columns`}</p>
                <p className='text-11 text-gray-9'>{t`Click a column to add it`}</p>
              </div>
              <span className='rounded-full bg-gray-3 px-2 py-0.5 text-11 font-semibold text-gray-11'>
                {unselected.length}
              </span>
            </div>
            <InputText
              leftSection={
                <Icon className='size-3.5 text-gray-9' name='lucide:search' />
              }
              placeholder={t`Search columns...`}
              value={search}
              onChange={setSearch}
            />
          </header>

          <div className={cn('ez-scrollbar overflow-y-auto', LIST_HEIGHT)}>
            {available.length === 0 ? (
              <div className='flex h-full min-h-40 flex-col items-center justify-center gap-2 p-4 text-center'>
                <Icon className='size-6 text-gray-7' name='lucide:search-x' />
                <p className='text-13 text-gray-10'>
                  {unselected.length === 0
                    ? t`No more columns available.`
                    : t`No columns match "${search.trim()}".`}
                </p>
              </div>
            ) : (
              <ul className='flex flex-col gap-0.5 p-1.5'>
                {available.map((column) => {
                  const kind = kindOf(column)
                  return (
                    <li key={column.key}>
                      <button
                        className='group/add flex w-full items-center gap-2.5 rounded-lg px-2 py-1.5 text-left transition-all hover:bg-primary-1 active:scale-[0.98]'
                        title={t`${kindLabel[kind]} column · click to add`}
                        type='button'
                        onClick={() => addColumn(column.key)}
                      >
                        <span
                          aria-label={kindLabel[kind]}
                          className='flex size-7 shrink-0 items-center justify-center rounded-md bg-gray-2'
                          role='img'
                        >
                          {renderKindIcon(kind)}
                        </span>
                        <span className='min-w-0 flex-1'>
                          <span className='block truncate text-13 text-gray-12'>
                            {column.label}
                          </span>
                          {column.label.replace(/\s+/g, '_').toLowerCase() !==
                            column.key.toLowerCase() && (
                            <span className='block truncate text-11 text-gray-9'>
                              {column.key}
                            </span>
                          )}
                        </span>
                        <span className='flex size-6 shrink-0 items-center justify-center rounded-md border border-gray-4 text-gray-9 transition-colors group-hover/add:border-primary-6 group-hover/add:bg-primary-9 group-hover/add:text-text-on-accent'>
                          <Icon className='size-3.5' name='lucide:plus' />
                        </span>
                      </button>
                    </li>
                  )
                })}
              </ul>
            )}
          </div>
        </section>
      </div>

      {/* Live preview */}
      <section className='flex flex-col overflow-hidden rounded-xl border border-gray-3 bg-surface shadow-sm'>
        <header className='flex items-center gap-2.5 border-b border-gray-3 bg-gray-1/60 px-3.5 py-2.5'>
          <span className='flex size-7 items-center justify-center rounded-lg bg-green-3 text-green-11'>
            <Icon className='size-4' name='lucide:table-2' />
          </span>
          <div className='min-w-0 flex-1'>
            <p className='text-13 font-semibold text-gray-13'>{t`Live preview`}</p>
            <p className='text-11 text-gray-9'>
              {isPreviewPending
                ? t`Running report...`
                : previewTotal !== null
                  ? t`Showing ${Math.min(previewRows.length, PREVIEW_ROWS)} of ${previewTotal} rows`
                  : t`Updates when you add or remove columns`}
            </p>
          </div>
          {isPreviewPending && (
            <Icon
              className='size-4 animate-spin text-primary-10'
              name='lucide:loader-2'
            />
          )}
          <Button
            color='gray'
            disabled={isPreviewPending || draft.fields.length === 0}
            icon='lucide:refresh-cw'
            label={t`Run again`}
            size='xs'
            variant='ghost'
            onClick={() => void runPreview()}
          />
        </header>
        <div className='p-3'>
          {previewError ? (
            <p className='rounded-lg border border-red-6 bg-red-2 px-3 py-2 text-12 text-red-11'>
              {previewError}
            </p>
          ) : (
            <div
              className={cn(
                'transition-opacity',
                isPreviewPending && previewRows.length > 0 && 'opacity-60',
              )}
            >
              <FieldsPreviewTable
                columns={previewColumns}
                fieldSettings={draft.fieldSettings}
                isLoading={isPreviewPending && previewRows.length === 0}
                maxRows={PREVIEW_ROWS}
                rows={previewRows}
                isLive
              />
            </div>
          )}
        </div>
      </section>
    </div>
  )
}

FieldsStepAgent.displayName = 'FieldsStepAgent'
export default FieldsStepAgent
