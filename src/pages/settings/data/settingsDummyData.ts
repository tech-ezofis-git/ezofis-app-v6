export const getDummyUserOptions = (
  users: SettingsUser[] = dummySettingsUsers,
): SettingsOption[] => {
  return users.map((user) => ({
    description: user.email,
    id: String(user.id),
    name: `${user.firstName} ${user.lastName}`.trim() || user.username,
    value: user.email,
  }))
}

export const getDummyGroupOptions = (
  groups: SettingsGroup[] = dummySettingsGroups,
) => {
  return groups.map((group) => ({
    caption: group.description,
    name: group.name,
  }))
}

export const getDummyGroupSelectOptions = (
  groups: SettingsGroup[] = dummySettingsGroups,
): SettingsOption[] => {
  return groups.map((group) => ({
    description: group.description,
    id: String(group.id),
    name: group.name,
    value: group.name,
  }))
}
